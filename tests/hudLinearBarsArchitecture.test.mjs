import { assert, assertStringIncludes } from "jsr:@std/assert";

Deno.test("HUD uses the labeled linear vitals surface and keeps the vitals event contract", async () => {
  const hud = await Deno.readTextFile("src/display/ui/hud.js");
  const bars = await Deno.readTextFile("src/display/ui/linearResourceBars.js");
  assertStringIncludes(hud, "createLinearResourceBars");
  assertStringIncludes(hud, "vitals.id = 'hud-vitals'");
  assertStringIncludes(hud, "window.addEventListener('ui:updateVitals'");
  assertStringIncludes(hud, "hpValue: hpVal");
  assertStringIncludes(hud, "staminaMax");
  assertStringIncludes(hud, "vitalsBars.set");
  assert(!hud.includes("vitalsGauge.set"), "HUD must not retain the removed circular gauge updater");
  assertStringIncludes(bars, "gridTemplateColumns: HUD_COLUMNS");
  assertStringIncludes(hud, "gridTemplateColumns: HUD_COLUMNS");
  const theme = await Deno.readTextFile("src/display/ui/hudTheme.js");
  assertStringIncludes(theme, "repeat(3, minmax(0, 1fr))");
  assertStringIncludes(hud, "topRightHud.appendChild(effectsHud)");
  assertStringIncludes(hud, "topRightHud.appendChild(questRow)");
  assert(!hud.includes("top: '84px'") && !hud.includes("top: '180px'"), "top HUD rows must flow without manual offsets");
  assertStringIncludes(hud, "minHeight: '40px'");
  assertStringIncludes(hud, "background: 'linear-gradient(180deg, rgba(49,39,18,0.94) 0%, rgba(22,18,10,0.94) 100%)'");
  assert(!hud.includes("statusHeader"), "effects start directly with square tiles");
  assertStringIncludes(hud, "overflowX: 'auto'");
  assertStringIncludes(bars, "label.textContent = def.shortLabel");
  assertStringIncludes(bars, "track.setAttribute('aria-label', def.label)");
  for (const short of ['H', 'M', 'S']) assertStringIncludes(bars, `shortLabel: '${short}'`);
  assertStringIncludes(bars, "label: 'Health'");
  assertStringIncludes(bars, "label: 'Mana'");
  assertStringIncludes(bars, "label: 'Stamina'");
  assertStringIncludes(bars, "value.textContent = '— / —'");
  assertStringIncludes(bars, "justifyContent: 'space-between'");
  assertStringIncludes(bars, "background: 'rgba(255,255,255,0.92)'");
  assertStringIncludes(bars, "borderRadius: '999px 0 0 999px'");
  assertStringIncludes(bars, "borderRadius: '0 999px 999px 0'");
  assertStringIncludes(bars, "resource.lagRatio");
  assertStringIncludes(bars, "const lostRatio = previousRatio - resolved.ratio");
  assertStringIncludes(bars, "recentChange.style.left = width");
  assertStringIncludes(bars, "requestAnimationFrame");
  assertStringIncludes(bars, "The colored fill is authoritative and immediate");
  assert(!hud.includes("createConcentricGauge"), "player HUD should not instantiate the circular gauge");
});
