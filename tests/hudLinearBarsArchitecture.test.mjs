import { assert, assertStringIncludes } from "jsr:@std/assert";

Deno.test("HUD uses the labeled linear vitals surface and keeps the vitals event contract", async () => {
  const hud = await Deno.readTextFile("src/display/ui/hud.js");
  const bars = await Deno.readTextFile("src/display/ui/linearResourceBars.js");
  assertStringIncludes(hud, "createLinearResourceBars");
  assertStringIncludes(hud, "vitals.id = 'hud-vitals'");
  assertStringIncludes(hud, "window.addEventListener('ui:updateVitals'");
  assertStringIncludes(hud, "hpValue: hpVal");
  assertStringIncludes(hud, "staminaMax");
  assertStringIncludes(hud, "vitalsBars.set");
  assert(!hud.includes("vitalsGauge.set"), "HUD must not retain the removed circular gauge updater");
  assertStringIncludes(bars, "tableLayout: 'fixed'");
  assertStringIncludes(bars, "const resourceRow = document.createElement('tr')");
  assertStringIncludes(bars, "resourceRow.appendChild(row)");
  assertStringIncludes(hud, "top: '84px'");
  assertStringIncludes(hud, "height: 'auto'");
  assertStringIncludes(hud, "top: '14px'");
  assertStringIncludes(hud, "top: '180px'");
  assertStringIncludes(hud, "questControl.textContent = '\\uD83D\\uDCDC  Quests'");
  assertStringIncludes(hud, "background: 'linear-gradient(180deg, rgba(10, 13, 18, 0.90) 0%, rgba(10, 9, 8, 0.62) 100%)'");
  assertStringIncludes(hud, "minHeight: '76px'");
  assertStringIncludes(hud, "background: 'linear-gradient(180deg, rgba(49,39,18,0.94) 0%, rgba(22,18,10,0.94) 100%)'");
  assertStringIncludes(hud, "statusHeaderLabel.textContent = 'Status Effects'");
  assertStringIncludes(hud, "minHeight: '40px'");
  assertStringIncludes(bars, "label.textContent = def.label");
  assertStringIncludes(bars, "label: 'Health'");
  assertStringIncludes(bars, "label: 'Mana'");
  assertStringIncludes(bars, "label: 'Stamina'");
  assertStringIncludes(bars, "value.textContent = '— / —'");
  assertStringIncludes(bars, "justifyContent: 'space-between'");
  assert(!hud.includes("createConcentricGauge"), "player HUD should not instantiate the circular gauge");
});
